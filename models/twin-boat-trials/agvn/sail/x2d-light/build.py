"""Light two-colour X2D package for the AGVN sailboat (flag label fitted 2026-11-28).

Reuses the earlier two-part project (AGVN-sail.3mf: part 1 blackBody on filament 1,
part 2 greenLetters on filament 2, same placement) with fresh meshes, and the same X2D
machine and filament presets (black SUNLU PLA+ 2.0, green Bambu PLA Basic). The process
is the earlier one made as light as it will print: lightning infill (it grows only where
a top surface needs holding up), 2 walls, no supports unless the slicer reports floating
regions, then tree supports from the bed only.

  python3 build.py            # slice without supports
  python3 build.py --tree     # slice with bed-only tree supports
  python3 build.py --tree --two-nozzles   # black on nozzle 1 (left, AMS), green on nozzle 2
                                          # (right, external spool): no colour-change purge on one nozzle
  ... --no-tower       no prime tower: each nozzle switch still flushes into the purge chute
  ... --cooldown[=10]  after the print, both auxiliary fans and the exhaust fan at full speed
                       for N minutes (default 10), see models/lib/bambu_cooldown.py

The meshes come from ../boat.coscad (main = blackBody / greenLetters); the lettering there is
generated by letters.py and inlaid flush (2026-11-28, after the first two-colour print).
"""
from pathlib import Path
import json, re, subprocess, sys, zipfile
import trimesh
sys.path.insert(0, str(Path(__file__).resolve().parents[4]/'lib'))
from bambu_cooldown import with_cooldown
H = Path(__file__).resolve().parent; S = H.parent; A = S.parent
tree = '--tree' in sys.argv
two = '--two-nozzles' in sys.argv
notower = '--no-tower' in sys.argv
COOL = next((float(a.split('=')[1]) if '=' in a else 10.0 for a in sys.argv if a.startswith('--cooldown')), 0.0)
INFILL = next((a.split('=')[1] for a in sys.argv if a.startswith('--infill=')), '5%')
job = H/(('tree' if tree else 'nosupport') + ('-two-nozzles' if two else '') + ('-notower' if notower else '') + (f'-cool{COOL:g}' if COOL else '')); job.mkdir(exist_ok=True)

def mesh_xml(oid, m):
    v = ''.join(f'<vertex x="{x:.5f}" y="{y:.5f}" z="{z:.5f}" />' for x, y, z in m.vertices)
    t = ''.join(f'<triangle v1="{a}" v2="{b}" v3="{c}" />' for a, b, c in m.faces)
    return f'<object id="{oid}" type="model"><mesh><vertices>{v}</vertices><triangles>{t}</triangles></mesh></object>'
black, green = (trimesh.load_mesh(H/f'{n}.stl') for n in ('blackBody', 'greenLetters'))
obj = ('<model xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02" unit="millimeter" xml:lang="en-US" requiredextensions="p">\n'
       ' <metadata name="BambuStudio:3mfVersion">1</metadata>\n <resources>' + mesh_xml(1, black) + mesh_xml(2, green) + '</resources>\n <build/>\n</model>\n')
project = job/'AGVN-sail-light.3mf'
with zipfile.ZipFile(S/'AGVN-sail.3mf') as old, zipfile.ZipFile(project, 'w', zipfile.ZIP_DEFLATED) as out:
    for i in old.infolist():
        data = old.read(i)
        if i.filename == '3D/Objects/object_1.model': data = obj
        elif i.filename == 'Metadata/model_settings.config' and two:
            data = data.decode().replace('key="filament_maps" value="1 1"', 'key="filament_maps" value="1 2"').encode()
            assert b'value="1 2"' in data
        out.writestr(i, data)

process = json.loads((S/'tree/process.json').read_text())
process.update({'sparse_infill_pattern': 'lightning', 'sparse_infill_density': INFILL, 'wall_loops': '2',
                'top_shell_layers': '4', 'bottom_shell_layers': '3',
                'enable_support': '1' if tree else '0', 'support_type': 'tree(auto)', 'support_on_build_plate_only': '1',
                'enable_prime_tower': '0' if notower else '1'})
(job/'process.json').write_text(json.dumps(process, indent=2) + '\n')
machine = with_cooldown(json.loads((A/'machine.json').read_text()), COOL)
(job/'machine.json').write_text(json.dumps(machine, indent=2) + '\n')
out = job/'slice'; out.mkdir(exist_ok=True)
with (out/'slicer.log').open('w') as log:
    subprocess.run(['/Applications/BambuStudio.app/Contents/MacOS/BambuStudio', '--debug', '2',
                    '--load-settings', f'{job/"machine.json"};{job/"process.json"}',
                    '--load-filaments', f'{A/"filament.json"};{S/"green.json"}',
                    '--arrange', '0', '--orient', '0', '--slice', '1',
                    '--export-3mf', 'AGVN-sail-light.gcode.3mf', '--outputdir', str(out), str(project)],
                   stdout=log, stderr=log, check=True)
r = json.loads((out/'result.json').read_text()); p = r['sliced_plates'][0]
code = (out/'plate_1.gcode').read_text()
features = {}
for f in re.findall(r'^; FEATURE: (.+)$', code, re.M): features[f] = features.get(f, 0) + 1
print(json.dumps({'job': job.name, 'return_code': r['return_code'], 'warning': p.get('warning_message'),
                  'hours': round(p['total_predication']/3600, 2),
                  'grams': {str(f.get('id')): round(f.get('total_used_g', 0), 1) for f in p['filaments']},
                  'support_paths': sum(v for k, v in features.items() if 'upport' in k),
                  'infill': process['sparse_infill_pattern'] + ' ' + process['sparse_infill_density'],
                  'prime_tower_paths': sum(v for k, v in features.items() if 'rime tower' in k),
                  'tool_changes': len(re.findall(r'^T[01]\b', code, re.M)),
                  'cooldown_min': COOL, 'cooldown_in_gcode': 'coscad rapid cool-down' in code}, indent=1))
