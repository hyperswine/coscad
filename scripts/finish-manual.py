#!/usr/bin/env python3
"""Add shared navigation and contained content to every generated manual page."""
import argparse
import html
import json
from pathlib import Path
import re
import posixpath

PAGES = [('index', 'Overview'), ('langextension', 'Language'),
         ('topological', 'Topological'), ('manufacturing', 'Manufacturing'),
         ('plan', 'Build plans'), ('lessons', 'Lessons'), ('syntax', 'Syntax modes'),
         ('examples', 'Examples'), ('tesseract', 'Tesseract'),
         ('changelog', 'Changelog'), ('man', 'man coscad'),
         ('orbit-tower', 'Orbit Tower notes')]


def navigation(prefix):
    links = ''.join(f'<a href="{prefix}{name}.html">{html.escape(title)}</a>' for name, title in PAGES)
    return (f'<nav class="top" aria-label="Main navigation"><div class="nav-inner">'
            f'<a class="brand" href="{prefix}index.html">CoScad</a>'
            f'<a href="{prefix}builds/index.html">Builds</a>'
            '<details class="nav-menu"><summary>Manual</summary>'
            f'<div class="nav-links">{links}</div></details></div></nav>')


def finish(root):
    # A missing render must fail before the atomic directory swap.
    for plan in (root / 'builds').glob('*/*_plan.json'):
        data = json.loads(plan.read_text())
        name = plan.name.removesuffix('_plan.json')
        for step in range(1, len(data['steps']) + 1):
            image = plan.with_name(f'{name}_step{step}.png')
            if not image.is_file() or image.stat().st_size == 0:
                raise ValueError(f'Missing instruction image: {image}')
    for path in root.rglob('*.html'):
        relative = path.relative_to(root)
        prefix = '../' * (len(relative.parts) - 1)
        text = path.read_text()
        text = re.sub(r'<nav class="top"[^>]*>.*?</nav>', '', text, flags=re.S)
        # The unquoted class generated by some pandoc templates is supported too.
        text = re.sub(r'<nav class=top\b[^>]*>.*?</nav>', '', text, flags=re.S)
        css = f'<link rel="stylesheet" href="{prefix}manual.css">'
        text = re.sub(r'<link\b(?=[^>]*href="(?:\.\./)*manual\.css")[^>]*>', '', text)
        text = text.replace('</head>', css + '</head>')
        if relative.parts[0] != 'builds':
            # Source links go to GitHub; documentation links stay in the manual.
            def link(match):
                value = match.group(1)
                if value.startswith(('https:', 'http:', '#', 'mailto:')):
                    return match.group(0)
                target, sep, anchor = value.partition('#')
                doc = Path(target).stem.lower()
                if target.endswith('.md') and doc in {name for name, _ in PAGES} | {'readme'}:
                    return 'href="' + ('index' if doc == 'readme' else doc) + '.html' + (sep + anchor if sep else '') + '"'
                if target.endswith(('.md', '.coscad', '.assemble', '.json', '.py', '.hs')) or target.startswith(('docs/', '../', 'examples/', 'models/', 'experiments/')):
                    context = '' if relative.name in ['index.html', 'changelog.html', 'man.html'] else 'docs'
                    normalized = posixpath.normpath(posixpath.join(context, target))
                    return 'href="https://github.com/hyperswine/coscad/blob/main/' + html.escape(normalized, quote=True) + (sep + anchor if sep else '') + '"'
                return match.group(0)
            text = re.sub(r'href="([^"]+)"', link, text)
            if '<main class="manual-content">' not in text:
                text = re.sub(r'(<body[^>]*>)(.*?)(</body>)',
                          lambda m: m[1] + '<main class="manual-content">' + m[2] + '</main>' + m[3], text, flags=re.S)
        text = re.sub(r'(<body[^>]*>)', lambda m: m[1] + navigation(prefix), text, count=1)
        # Account for font size, safe areas and zoom when following anchors.
        if 'new ResizeObserver' not in text:
            script = """<script>(()=>{const nav=document.querySelector('nav.top');const update=()=>document.documentElement.style.setProperty('--nav-height',nav.offsetHeight+'px');update();if(window.ResizeObserver)new ResizeObserver(update).observe(nav);})();</script>"""
            text = text.replace('</body>',script+'</body>')
        path.write_text(text)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    finish(parser.parse_args().directory)
